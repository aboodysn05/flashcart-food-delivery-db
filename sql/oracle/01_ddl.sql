CREATE TABLE "User" (
    UserID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FirstName VARCHAR2(50) NOT NULL,
    LastName VARCHAR2(50) NOT NULL,
    Email VARCHAR2(100) NOT NULL UNIQUE,
    Password VARCHAR2(255) NOT NULL,
    UserType VARCHAR2(20) NOT NULL CHECK (UserType IN ('Customer', 'Staff', 'Driver', 'Admin')),
    RegistrationDate TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    LastLogin TIMESTAMP
);

CREATE TABLE UserPhone (
    UserID NUMBER NOT NULL,
    PhoneType VARCHAR2(20) NOT NULL CHECK (PhoneType IN ('Mobile', 'Home', 'Work')),
    PhoneNumber VARCHAR2(20) NOT NULL,
    CONSTRAINT pk_userphone PRIMARY KEY (UserID, PhoneType),
    CONSTRAINT fk_userphone_user FOREIGN KEY (UserID) REFERENCES "User"(UserID) ON DELETE CASCADE
);

CREATE TABLE Address (
    AddressID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserID NUMBER NOT NULL,
    AddressLine1 VARCHAR2(200) NOT NULL,
    AddressLine2 VARCHAR2(200),
    City VARCHAR2(50) NOT NULL,
    District VARCHAR2(50) NOT NULL,
    Landmark VARCHAR2(100),
    AddressType VARCHAR2(50) NOT NULL CHECK (AddressType IN ('Home', 'Work', 'Other')),
    IsDefault CHAR(1) DEFAULT 'N' NOT NULL CHECK (IsDefault IN ('Y', 'N')),
    CONSTRAINT fk_address_user FOREIGN KEY (UserID) REFERENCES "User"(UserID) ON DELETE CASCADE
);

CREATE TABLE Customer (
    CustomerID NUMBER PRIMARY KEY,
    PreferedPaymentMethod VARCHAR2(30),
    CONSTRAINT fk_customer_user FOREIGN KEY (CustomerID) REFERENCES "User"(UserID) ON DELETE CASCADE
);

CREATE TABLE Region (
    RegionID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RegionName VARCHAR2(100) NOT NULL,
    Country VARCHAR2(50) NOT NULL,
    City VARCHAR2(50) NOT NULL
);

CREATE TABLE Hub (
    HubID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RegionID NUMBER NOT NULL,
    HubName VARCHAR2(100) NOT NULL,
    LocationCoordinates VARCHAR2(100) NOT NULL,
    Capacity NUMBER DEFAULT 50 NOT NULL,
    ContactNumber VARCHAR2(20) NOT NULL,
    ManagerID NUMBER UNIQUE,
    CONSTRAINT fk_hub_region FOREIGN KEY (RegionID) REFERENCES Region(RegionID)
);

CREATE TABLE Staff (
    StaffID NUMBER PRIMARY KEY,
    HubID NUMBER,
    StaffRole VARCHAR2(50) NOT NULL,
    HireDate DATE NOT NULL,
    CONSTRAINT fk_staff_user FOREIGN KEY (StaffID) REFERENCES "User"(UserID) ON DELETE CASCADE,
    CONSTRAINT fk_staff_hub FOREIGN KEY (HubID) REFERENCES Hub(HubID) ON DELETE SET NULL
);

ALTER TABLE Hub ADD CONSTRAINT fk_hub_manager FOREIGN KEY (ManagerID) REFERENCES Staff(StaffID) ON DELETE SET NULL;

CREATE TABLE Driver (
    DriverID NUMBER PRIMARY KEY,
    VehicleType VARCHAR2(20) NOT NULL CHECK (VehicleType IN ('Bike', 'Scooter', 'Car')),
    LicenseNumber VARCHAR2(50) NOT NULL UNIQUE,
    isAvailable CHAR(1) DEFAULT 'Y' NOT NULL CHECK (isAvailable IN ('Y', 'N')),
    CurrentLocationGPS VARCHAR2(100),
    Rating NUMBER(2,1) DEFAULT 0 CHECK (Rating BETWEEN 0 AND 5),
    RegistrationDate TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_driver_user FOREIGN KEY (DriverID) REFERENCES "User"(UserID) ON DELETE CASCADE
);


CREATE TABLE Restaurant (
    RestaurantID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RestaurantName VARCHAR2(100) NOT NULL,
    CuisineType VARCHAR2(50) NOT NULL,
    PhoneNumber VARCHAR2(20) NOT NULL,
    Email VARCHAR2(100) NOT NULL UNIQUE,
    RegistrationDate DATE DEFAULT CURRENT_DATE NOT NULL,
    Rating NUMBER(2,1) DEFAULT 0 CHECK (Rating BETWEEN 0 AND 5),
    Status VARCHAR2(20) DEFAULT 'Pending' NOT NULL CHECK (Status IN ('Active', 'Suspended', 'Pending'))
);

CREATE TABLE RestaurantOperatingHours (
    RestaurantID NUMBER NOT NULL,
    DayOfWeek VARCHAR2(10) NOT NULL CHECK (DayOfWeek IN ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday')),
    OpeningTime VARCHAR2(8) NOT NULL,
    ClosingTime VARCHAR2(8) NOT NULL,
    CONSTRAINT pk_rest_hours PRIMARY KEY (RestaurantID, DayOfWeek),
    CONSTRAINT fk_resthours_rest FOREIGN KEY (RestaurantID) REFERENCES Restaurant(RestaurantID) ON DELETE CASCADE
);

CREATE TABLE Menu (
    MenuID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RestaurantID NUMBER NOT NULL,
    MenuName VARCHAR2(100) NOT NULL,
    IsActive CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IsActive IN ('Y', 'N')),
    ValidFrom DATE NOT NULL,
    ValidTo DATE,
    CONSTRAINT fk_menu_rest FOREIGN KEY (RestaurantID) REFERENCES Restaurant(RestaurantID) ON DELETE CASCADE
);

CREATE TABLE MenuCategory (
    MenuCategoryID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CategoryName VARCHAR2(50) NOT NULL,
    Description VARCHAR2(200),
    DisplayOrder NUMBER DEFAULT 0 NOT NULL
);

CREATE TABLE MenuItem (
    MenuItemID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MenuID NUMBER NOT NULL,
    ItemName VARCHAR2(100) NOT NULL,
    Description VARCHAR2(500),
    BasePrice NUMBER(10,2) NOT NULL CHECK (BasePrice >= 0),
    PreparationTime NUMBER DEFAULT 0 NOT NULL CHECK (PreparationTime >= 0),
    IsAvailable CHAR(1) DEFAULT 'Y' NOT NULL CHECK (IsAvailable IN ('Y', 'N')),
    CONSTRAINT fk_menuitem_menu FOREIGN KEY (MenuID) REFERENCES Menu(MenuID) ON DELETE CASCADE
);

CREATE TABLE MenuItemCategory (
    MenuItemID NUMBER NOT NULL,
    MenuCategoryID NUMBER NOT NULL,
    CONSTRAINT pk_menuitem_cat PRIMARY KEY (MenuItemID, MenuCategoryID),
    CONSTRAINT fk_mic_item FOREIGN KEY (MenuItemID) REFERENCES MenuItem(MenuItemID) ON DELETE CASCADE,
    CONSTRAINT fk_mic_cat FOREIGN KEY (MenuCategoryID) REFERENCES MenuCategory(MenuCategoryID) ON DELETE CASCADE
);


CREATE TABLE "Order" (
    OrderID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CustomerID NUMBER NOT NULL,
    HubID NUMBER NOT NULL,
    DriverID NUMBER,
    OrderTimestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DeliveryFee NUMBER(10,2) DEFAULT 0 NOT NULL CHECK (DeliveryFee >= 0),
    OrderStatus VARCHAR2(20) DEFAULT 'Pending' NOT NULL CHECK (OrderStatus IN ('Pending', 'Preparing', 'Ready', 'Out for Delivery', 'Delivered', 'Cancelled')),
    EstimatedDeliveryTime TIMESTAMP NOT NULL,
    ActualDeliveryTime TIMESTAMP,
    CONSTRAINT fk_order_customer FOREIGN KEY (CustomerID) REFERENCES Customer(CustomerID),
    CONSTRAINT fk_order_hub FOREIGN KEY (HubID) REFERENCES Hub(HubID),
    CONSTRAINT fk_order_driver FOREIGN KEY (DriverID) REFERENCES Driver(DriverID)
);

CREATE TABLE OrderItem (
    OrderID NUMBER NOT NULL,
    LineNumber NUMBER NOT NULL,
    MenuItemID NUMBER NOT NULL,
    Quantity NUMBER NOT NULL CHECK (Quantity > 0),
    UnitPriceAtTimeOfOrder NUMBER(10,2) NOT NULL CHECK (UnitPriceAtTimeOfOrder >= 0),
    SpecialInstructions VARCHAR2(500),
    CONSTRAINT pk_orderitem PRIMARY KEY (OrderID, LineNumber),
    CONSTRAINT fk_oi_order FOREIGN KEY (OrderID) REFERENCES "Order"(OrderID) ON DELETE CASCADE,
    CONSTRAINT fk_oi_item FOREIGN KEY (MenuItemID) REFERENCES MenuItem(MenuItemID)
);

CREATE TABLE Payment (
    PaymentID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderID NUMBER NOT NULL UNIQUE,
    Amount NUMBER(10,2) NOT NULL CHECK (Amount >= 0),
    PaymentMethod VARCHAR2(30) NOT NULL CHECK (PaymentMethod IN ('Cash', 'Credit Card', 'Wallet')),
    PaymentStatus VARCHAR2(20) DEFAULT 'Pending' NOT NULL CHECK (PaymentStatus IN ('Pending', 'Success', 'Failed')),
    TransactionReference VARCHAR2(100) NOT NULL UNIQUE,
    PaymentTimestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_payment_order FOREIGN KEY (OrderID) REFERENCES "Order"(OrderID) ON DELETE CASCADE
);

CREATE TABLE Review (
    ReviewID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderID NUMBER NOT NULL UNIQUE,
    RestaurantID NUMBER NOT NULL,
    DriverID NUMBER,
    RestaurantRating NUMBER(2,1) NOT NULL CHECK (RestaurantRating BETWEEN 1 AND 5),
    DriverRating NUMBER(2,1) CHECK (DriverRating BETWEEN 1 AND 5),
    "Comment" VARCHAR2(1000),
    ReviewTimestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_review_order FOREIGN KEY (OrderID) REFERENCES "Order"(OrderID) ON DELETE CASCADE,
    CONSTRAINT fk_review_rest FOREIGN KEY (RestaurantID) REFERENCES Restaurant(RestaurantID) ON DELETE CASCADE,
    CONSTRAINT fk_review_driver FOREIGN KEY (DriverID) REFERENCES Driver(DriverID) ON DELETE SET NULL
);

CREATE TABLE AuditLog (
    AuditID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserID NUMBER NOT NULL,
    Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ActionType VARCHAR2(20) NOT NULL CHECK (ActionType IN ('INSERT', 'UPDATE', 'DELETE')),
    TableName VARCHAR2(128) NOT NULL,
    RecordID VARCHAR2(255),
    ColumnName VARCHAR2(128),
    OldValue VARCHAR2(4000),
    NewValue VARCHAR2(4000),
    CONSTRAINT fk_audit_user FOREIGN KEY (UserID) REFERENCES "User"(UserID) ON DELETE CASCADE
);

CREATE TABLE GPSLog (
    GPSLogID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DriverID NUMBER NOT NULL,
    Latitude NUMBER(9,6) NOT NULL,
    Longitude NUMBER(9,6) NOT NULL,
    Timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_gpslog_driver FOREIGN KEY (DriverID) REFERENCES Driver(DriverID) ON DELETE CASCADE
);

